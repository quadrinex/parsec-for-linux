# shellcheck shell=bash
# Common runtime environment: isolated wine-staging + dedicated prefix.
# Source it: . runtime/env.sh
# Never touches the system wine (/usr/bin/wine) or ~/.wine.

PLH_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PLH_RUNTIME="$PLH_ROOT/runtime"
PLH_DL="$PLH_RUNTIME/downloads"
PLH_PFX="$PLH_RUNTIME/prefix"
PLH_TRACES="$PLH_RUNTIME/traces"
# Data outside the repository if PLH_DATA_DIR is set, or if the repository is not writable (e.g. /opt).
if [ -z "${PLH_DATA_DIR:-}" ] && [ ! -w "$PLH_RUNTIME" ]; then
    PLH_DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/parsec-for-linux"
fi
if [ -n "${PLH_DATA_DIR:-}" ]; then
    PLH_DL="$PLH_DATA_DIR/downloads"; PLH_PFX="$PLH_DATA_DIR/prefix"; PLH_TRACES="$PLH_DATA_DIR/traces"
    mkdir -p "$PLH_DL" "$PLH_TRACES"
fi

# Load the user configuration (generated by bin/parsec-config-ui) if present.
if [ -f "$PLH_RUNTIME/config.env" ]; then
    # shellcheck disable=SC1091
    . "$PLH_RUNTIME/config.env"
fi

WINE_STAGING_VER="11.20"
WINE_STAGING_NAME="wine-${WINE_STAGING_VER}-staging-amd64"
WINE_STAGING_URL="https://github.com/Kron4ek/Wine-Builds/releases/download/${WINE_STAGING_VER}/${WINE_STAGING_NAME}.tar.xz"
WINE_STAGING_SHA256="1dc66e214019b747e98955e5dba3ff650fdb5f11354557ac75ac14034a53f688"

DXVK_VER="3.1.1"
DXVK_URL="https://github.com/doitsujin/dxvk/releases/download/v${DXVK_VER}/dxvk-${DXVK_VER}.tar.gz"
DXVK_SHA256="40565b4a724aadc4433fa4e010b4b23916d9b1f1baeee64e17186db94f54e608"

PARSEC_URL="https://builds.parsec.app/package/parsec-windows.exe"

PLH_WINE_DIR="$PLH_DL/$WINE_STAGING_NAME"          # Kron4ek wine-staging as is
PLH_WINE_PLH_DIR="$PLH_DL/wine-plh-$WINE_STAGING_VER" # same tree + patched PE modules (build-wine-plh.sh)
PLH_DXVK_DIR="$PLH_DL/dxvk-$DXVK_VER"

export WINEPREFIX="$PLH_PFX"
export WINEARCH=win64
# PLH_WINE_FLAVOR=staging forces the unpatched wine-staging (for comparison).
if [ "${PLH_WINE_FLAVOR:-plh}" = plh ] && [ -x "$PLH_WINE_PLH_DIR/bin/wine" ]; then PLH_WINE_BIN="$PLH_WINE_PLH_DIR/bin"
else PLH_WINE_BIN="$PLH_WINE_DIR/bin"; fi
export PATH="$PLH_WINE_BIN:$PATH"
export WINE="$PLH_WINE_BIN/wine"
export WINESERVER="$PLH_WINE_BIN/wineserver"
# No XDG menus/associations created in the user's session.
export WINEDLLOVERRIDES="${WINEDLLOVERRIDES:+$WINEDLLOVERRIDES;}winemenubuilder.exe=d"
: "${WINEDEBUG:=-all}"
export WINEDEBUG

PARSEC_DIR_WIN='C:\users\'"$USER"'\AppData\Roaming\Parsec'
mkdir -p "$PLH_TRACES"
